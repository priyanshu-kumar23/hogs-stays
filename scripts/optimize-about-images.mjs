// Optimise the About-page photographs.  Usage: `npm run images:about`
//   raw-images/about/<camera file>  ->  public/images/about/<seo-name>-<width>.webp   (+ lib/aboutImages.generated.ts)
// WebP q78, widths 640/1280/1920 (never upscaled), EXIF auto-rotate, all metadata (incl. GPS) stripped. Originals are only read.
import sharp from 'sharp';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public', 'images', 'about');
const WIDTHS = [640, 1280, 1920];
const photos = [
  { key: 'building', source: 'SAL_9407.JPG', slug: 'hogs-manali-building-exterior-hogs-gate-misty-mountains', alt: 'HOGS Panorama building and entrance gate in Manali with misty mountains', caption: 'The HOGS gate and the building, wrapped in mountain mist', position: 'center 50%' },
  { key: 'gazal', source: 'SAL_0847.JPG', slug: 'hogs-founder-gazal-cafe-do-nthng-terrace-manali', alt: 'Gazal, co-founder of HOGS, on the Cafe DO NTHNG terrace in Manali beside the House of Gaz and Saloni mural', caption: 'Gazal', position: 'center 58%' },
  { key: 'saloni', source: 'SAL_0856.JPG', slug: 'hogs-founder-saloni-cafe-do-nthng-terrace-manali', alt: 'Saloni, co-founder of HOGS, at the Cafe DO NTHNG terrace in Manali', caption: 'Saloni', position: 'center 55%' },
  { key: 'friends', source: 'SAL_0426.JPG', slug: 'hogs-founders-gazal-saloni-with-friends-hogs-sign-manali', alt: 'Gazal and Saloni, founders of HOGS, with friends beside the HOGS sign in Manali', caption: 'Gazal & Saloni with friends at HOGS.', position: 'center 50%' },
];
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
const kb = n => `${(n / 1024).toFixed(0)} KB`;
const entries = {};
for (const p of photos) {
  const rotated = await sharp(join(ROOT, 'raw-images', 'about', p.source), { failOn: 'none' }).rotate().toBuffer({ resolveWithObject: true });
  const { data, info } = rotated;
  const widths = WIDTHS.filter(w => w <= info.width);
  const srcSet = [];
  for (const w of widths) {
    const buf = await sharp(data).resize({ width: w, withoutEnlargement: true }).webp({ quality: 78, effort: 5 }).toBuffer();
    writeFileSync(join(OUT, `${p.slug}-${w}.webp`), buf);
    srcSet.push({ width: w, src: `/images/about/${p.slug}-${w}.webp`, bytes: buf.length });
  }
  const blur = await sharp(data).resize({ width: 24 }).webp({ quality: 40 }).toBuffer();
  console.log(p.slug.padEnd(62), `${info.width}x${info.height}`, srcSet.map(s => `${s.width}:${kb(s.bytes)}`).join(' '));
  entries[p.key] = {
    id: p.slug, src: srcSet.find(s => s.width === 1280).src, srcSet: srcSet.map(({ width, src }) => ({ width, src })),
    width: info.width, height: info.height, alt: p.alt, caption: p.caption, position: p.position,
    blurDataURL: `data:image/webp;base64,${blur.toString('base64')}`,
  };
}
writeFileSync(join(ROOT, 'lib', 'aboutImages.generated.ts'),
  `// GENERATED by scripts/optimize-about-images.mjs (npm run images:about). Do not edit by hand.\nexport type AboutImage = { id: string; src: string; srcSet: { width: number; src: string }[]; width: number; height: number; alt: string; caption: string; position: string; blurDataURL: string };\nexport const aboutImages = ${JSON.stringify(entries, null, 2)} as const satisfies Record<string, AboutImage>;\n`);
